const cron = require('node-cron');
const Inventory = require('../models/Inventory');
const emailService = require('./emailService');

let cronTask = null;

/**
 * Scans MongoDB for items whose stock is strictly less than threshold.
 * Formulates detailed HTML notification and dispatches to ADMIN_EMAIL.
 * Returns array of flagged alert items.
 */
async function checkLowStockNow() {
  try {
    // Strictly compare stock to its own threshold (boundary: stock < threshold)
    const lowStockItems = await Inventory.find({
      $expr: { $lt: ['$stock', '$threshold'] }
    }).sort({ stock: 1 });

    const formattedAlerts = lowStockItems.map((item) => ({
      itemId: item._id.toString(),
      _id: item._id.toString(),
      name: item.name,
      category: item.category,
      stock: Math.max(0, item.stock),
      threshold: item.threshold
    }));

    if (formattedAlerts.length === 0) {
      return [];
    }

    // Generate Responsive HTML Email
    const adminEmail = process.env.ADMIN_EMAIL || process.env.EMAIL_USER || 'admin@pizzadelivery.com';
    const htmlTableRows = formattedAlerts
      .map(
        (i) => `
        <tr style="border-bottom: 1px solid #e9ecef;">
          <td style="padding: 12px; font-weight: 600; color: #212529;">${i.name}</td>
          <td style="padding: 12px; text-transform: capitalize; color: #6c757d;">${i.category}</td>
          <td style="padding: 12px; font-weight: bold; color: ${i.stock === 0 ? '#dc3545' : '#fd7e14'};">
            ${i.stock} ${i.stock === 0 ? '(OUT OF STOCK)' : 'units'}
          </td>
          <td style="padding: 12px; color: #495057;">${i.threshold} units</td>
        </tr>`
      )
      .join('');

    const htmlContent = `
      <!DOCTYPE html>
      <html>
      <head>
        <meta charset="utf-8">
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background: #f8f9fa; padding: 20px; }
          .container { max-width: 650px; margin: 0 auto; background: #ffffff; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 6px rgba(0,0,0,0.05); }
          .header { background: #e63946; padding: 20px; color: #ffffff; text-align: center; }
          .content { padding: 24px; }
          table { width: 100%; border-collapse: collapse; margin-top: 16px; font-size: 14px; }
          th { background: #f1f3f5; padding: 10px; text-align: left; font-weight: 600; }
          .footer { background: #f8f9fa; padding: 12px; text-align: center; font-size: 12px; color: #6c757d; }
        </style>
      </head>
      <body>
        <div class="container">
          <div class="header">
            <h2 style="margin: 0;">⚠️ Low Stock Inventory Alert</h2>
            <p style="margin: 4px 0 0; font-size: 14px;">Pizza Delivery Admin Alert System</p>
          </div>
          <div class="content">
            <p>The automated inventory monitor detected <strong>${formattedAlerts.length}</strong> ingredient(s) below operational thresholds:</p>
            <table>
              <thead>
                <tr>
                  <th>Item Name</th>
                  <th>Category</th>
                  <th>Current Stock</th>
                  <th>Threshold</th>
                </tr>
              </thead>
              <tbody>
                ${htmlTableRows}
              </tbody>
            </table>
            <p style="margin-top: 20px;">Please login to the Admin Inventory Dashboard to restock depleted items immediately.</p>
          </div>
          <div class="footer">
            Automated notification generated by Pizza Delivery Cron Service.
          </div>
        </div>
      </body>
      </html>
    `;

    const textContent = `Low Stock Alert:\n` +
      formattedAlerts.map(i => `- ${i.name} (${i.category}): ${i.stock}/${i.threshold} units`).join('\n');

    await emailService.sendMail({
      to: adminEmail,
      subject: `⚠️ URGENT: Low Stock Alert (${formattedAlerts.length} items) — Pizza Delivery`,
      html: htmlContent,
      text: textContent
    });

    return formattedAlerts;
  } catch (error) {
    console.error('[CronService] Error evaluating low stock:', error.message);
    if (process.env.NODE_ENV === 'test') {
      throw error;
    }
    return [];
  }
}

/**
 * Starts scheduled background cron worker.
 */
function startCronJob(scheduleOverride) {
  const schedule = scheduleOverride || process.env.CRON_SCHEDULE || '0 */1 * * *';

  if (cronTask) {
    cronTask.stop();
  }

  cronTask = cron.schedule(schedule, async () => {
    console.log('[CronService] Executing scheduled inventory health check...');
    await checkLowStockNow();
  });

  console.log(`[CronService] Low-stock monitor scheduled: ${schedule}`);
  return cronTask;
}

/**
 * Stops active cron task (for testing and graceful shutdown).
 */
function stopCronJob() {
  if (cronTask) {
    cronTask.stop();
    cronTask = null;
  }
}

module.exports = {
  checkLowStockNow,
  checkLowStock: checkLowStockNow,
  startCronJob,
  start: startCronJob,
  stopCronJob,
  stop: stopCronJob
};
